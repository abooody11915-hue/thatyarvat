function dbQuery(table, method, body, filter) {
  if (!method) method = "GET";
  if (!filter) filter = "";
  var url = SUPABASE_URL + "/rest/v1/" + table + filter;
  var opts = {
    method: method,
    headers: Object.assign({}, HEADERS, { "Content-Type": "application/json", "Prefer": method === "POST" ? "return=representation" : "" }),
  };
  if (body) opts.body = JSON.stringify(body);
  return fetch(url, opts).then(function(res) {
    if (!res.ok) return null;
    return res.text().then(function(t) { return t ? JSON.parse(t) : null; });
  }).catch(function(e) { console.error(e); return null; });
}

